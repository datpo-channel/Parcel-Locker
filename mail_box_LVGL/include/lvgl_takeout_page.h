#ifndef LVGL_TAKEOUT_PAGE_H_
#define LVGL_TAKEOUT_PAGE_H_

#include "lvgl.h"
#include "ui_context.h"

/**************************************************************************
 *
 *   @brief : 创建取件码 LVGL 界面 (背景 + 二维码 + 取件码输入框 + 数字键盘)
 *   @arg   : ui   指向 ui_context_t 结构体的指针
 *
 *   @retval: 成功返回 0，失败返回 -1
 *
 ***************************************************************************/
int lvgl_takeout_create(ui_context_t *ui);

/**************************************************************************
 *
 *   @brief : 销毁取件码界面，释放 LVGL 对象
 *
 ***************************************************************************/
void lvgl_takeout_destroy(void);

/**************************************************************************
 *
 *   @brief : 获取当前用户的操作结果 (按键码)
 *   @arg   : ui   指向 ui_context_t 结构体的指针
 *
 *   @retval: -1              操作超时
 *            RET_SCAN_PICKUP(5)  扫码取件通知中断（与其他页面一致）
 *            UI_KEY_CONFIRM  确认键（4 位取件码输满后生效）
 *            UI_KEY_BACK     返回键
 *            UI_KEY_QUERY    查询键
 *   @note  : 数字键(0-9)/删除键仅更新输入状态，不作为 action 返回；
 *            取件码通过 lvgl_takeout_get_code 读取
 *
 ***************************************************************************/
int lvgl_takeout_get_action(ui_context_t *ui);

/**************************************************************************
 *
 *   @brief : 设置/更新二维码图片（JPG 经 libjpeg 解码后显示，保持原始大小）
 *   @arg   : qr_path  二维码 JPG 路径
 *
 *   @retval: 成功返回 0，失败返回 -1
 *
 ***************************************************************************/
int lvgl_takeout_set_qr(const char *qr_path);

/**************************************************************************
 *
 *   @brief : 获取当前已输入的 4 位取件码
 *   @arg   : code      输出缓冲区 (至少 5 字节)
 *   @arg   : code_size 缓冲区大小
 *
 *   @retval: 成功返回 0，失败返回 -1
 *
 ***************************************************************************/
int lvgl_takeout_get_code(char *code, size_t code_size);

#endif /* LVGL_TAKEOUT_PAGE_H_ */
