#ifndef LVGL_LOGIN_PAGE_H_
#define LVGL_LOGIN_PAGE_H_

#include "lvgl.h"
#include "ui_context.h"

/**************************************************************************
 *
 *   @brief : 创建 LVGL 登录界面 (背景 + 输入框 + 数字键盘 + 功能按钮)
 *   @arg   : ui           指向 ui_context_t 结构体的指针
 *   @arg   : bg_sjpg_path 背景 sjpg 路径
 *
 *   @retval: 成功返回 0，失败返回 -1
 *
 ***************************************************************************/
int lvgl_login_create(ui_context_t *ui, const char *bg_sjpg_path);

/**************************************************************************
 *
 *   @brief : 销毁登录界面，释放 LVGL 对象
 *
 ***************************************************************************/
void lvgl_login_destroy(void);

/**************************************************************************
 *
 *   @brief : 清空验证码输入
 *
 ***************************************************************************/
void lvgl_login_clear_code(void);

/**************************************************************************
 *
 *   @brief : 获取当前用户的操作结果
 *   @arg   : ui   指向 ui_context_t 结构体的指针
 *
 *   @retval: -1              无操作 (超时或无输入)
 *            0-9             数字键
 *            UI_KEY_DELETE   删除键
 *            UI_KEY_CONFIRM  确认键 (登录按钮)
 *            UI_KEY_BACK     返回键
 *            UI_KEY_QUERY    获取验证码按钮
 *
 ***************************************************************************/
int lvgl_login_get_action(ui_context_t *ui);

/**************************************************************************
 *
 *   @brief : 获取已输入的手机号
 *   @arg   : phone 输出缓冲区 (至少 12 字节)
 *
 *   @retval: 成功返回 0，失败返回 -1
 *
 ***************************************************************************/
int lvgl_login_get_phone(char *phone, size_t phone_size);

/**************************************************************************
 *
 *   @brief : 获取已输入的验证码
 *   @arg   : code 输出缓冲区 (至少 5 字节)
 *
 *   @retval: 成功返回 0，失败返回 -1
 *
 ***************************************************************************/
int lvgl_login_get_code(char *code, size_t code_size);

#endif /* LVGL_LOGIN_PAGE_H_ */