#ifndef SMS_H
#define SMS_H

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/**************************************************************************
 *
 *   @brief : 发送短信验证码到指定手机号
 *   @arg   : phone  目标手机号（11位）
 *   @arg   : code   要发送的验证码（4-6位数字）
 *
 *   @retval: 0  发送成功
 *           -1 参数错误（手机号或验证码为空）
 *           -2 网络连接失败
 *           -3 数据发送失败
 *           -4 读取响应失败
 *           -5 获取短信平台密码失败
 *           -6 短信平台业务拒绝（欠费/号码无效/内容审核，code != 2）
 *   @note  : 使用互亿无线短信接口
 *            账号密码由云端 /sms_key 接口动态获取
 *            该函数会阻塞等待响应，超时时间约5秒
 *            适用场景：存件、快递员登录、查询等需要手机验证的流程
 *
 ***************************************************************************/
int send_sms_code(const char *phone, const char *code);

/**************************************************************************
 *
 *   @brief : 向手机号发送短信验证码（带冷却与轰炸防护）
 *   @arg   : phone  目标手机号（11位，以 1 开头）
 *
 *   @retval: 0  发送成功
 *           1  冷却中（同号 60 秒冷却，或任意两次发码间隔不足 60 秒）
 *           其他  send_sms_code 返回的错误码
 *   @note  : 成功后记入 g_last_sms_* 供 verify_phone_code 校验；
 *            Demo 账号(DEMO_PHONE)免真实短信，固定验证码 DEMO_CODE；
 *            不打印明文验证码到日志
 *
 ***************************************************************************/
int request_sms_code(const char *phone);

#endif // SMS_H