#ifndef PICKUP_MONITOR_H_
#define PICKUP_MONITOR_H_

/**************************************************************************
 *
 *   @brief : 启动扫码取件后台监控线程
 *
 *   @retval: 成功返回 0，失败返回 -1
 *   @note  : 后台线程每 3 秒轮询所有有取件令牌的占用柜，
 *            发现网页端验证完成后设置通知标志，由主线程开箱
 *
 ***************************************************************************/
int ui_start_pickup_watcher(void);

/**************************************************************************
 *
 *   @brief : 检查是否有扫码取件通知（非阻塞）
 *
 *   @retval: 1  有待处理的扫码取件
 *            0  无通知
 *
 ***************************************************************************/
int ui_check_pickup_notify(void);

/**************************************************************************
 *
 *   @brief : 清除扫码取件通知标志
 *
 *   @retval: 无
 *
 ***************************************************************************/
void ui_clear_pickup_notify(void);

#endif