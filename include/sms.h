#ifndef SMS_H
#define SMS_H

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/**************************************************************************
 *
 *   @brief : 发送短信验证码到指定手机号
 *   @arg   : phone  目标手机号（11位）
 *   @arg   : code   要发送的验证码（4-6位数字）
 *
 *   @retval: 0  发送成功
 *           -1 参数错误（手机号或验证码为空）
 *           -2 网络连接失败
 *           -3 数据发送失败
 *           -4 读取响应失败
 *   @note  : 使用互亿无线短信接口
 *            账号密码在 sms.c 中配置（建议后续移至配置文件）
 *            该函数会阻塞等待响应，超时时间约5秒
 *            适用场景：存件、快递员登录、查询等需要手机验证的流程
 *
 ***************************************************************************/
int send_sms_code(const char *phone, const char *code);

#endif // SMS_H