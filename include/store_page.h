#ifndef STORE_PAGE_H_
#define STORE_PAGE_H_

#include "ui_context.h"

/**************************************************************************
 *
 *   @brief : 显示存物信息输入界面，等待用户输入全部信息
 *   @arg   : ui       指向 ui_context_t 结构体的指针
 *   @arg   : phone    输出缓冲区，用于存储11位手机号
 *   @arg   : code     输出缓冲区，用于存储4位自定义取件码
 *   @arg   : box_size 输出，选择的箱体大小 (1=小, 2=中, 3=大)
 *   @arg   : duration 输出，存放时长 (1/2/4/8 小时)
 *
 *   @retval: 成功返回 0，失败返回 -1
 *   @note  : 阻塞等待，用户点击确认键且所有字段填写完整后返回
 *
 ***************************************************************************/
int show_store_info(ui_context_t *ui, char *phone, char *code,
                    int *box_size, int *duration);

/**************************************************************************
 *
 *   @brief : 存件成功后显示成功页面，等待用户触摸后返回
 *   @arg   : ui    指向 ui_context_t 结构体的指针
 *
 *   @retval: 无
 *   @note  : 显示 send_success.jpg 背景
 *
 ***************************************************************************/
void show_send_success(ui_context_t *ui);

/**************************************************************************
 *
 *   @brief : 显示支付界面，等待用户选择支付或取消
 *   @arg   : ui    指向 ui_context_t 结构体的指针
 *
 *   @retval: 1  用户点击"我已支付"
 *            0  用户点击"取消支付"
 *   @note  : 显示 pay_info.jpg 背景
 *
 ***************************************************************************/
int show_pay_info(ui_context_t *ui);

#endif